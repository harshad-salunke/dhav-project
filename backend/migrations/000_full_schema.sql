-- ============================================================================
-- DHAV — FULL DATABASE SCHEMA (single source of truth, current state)
-- ============================================================================
-- This ONE file recreates the ENTIRE schema as it exists today. It already
-- includes every column added by later migrations, so it is equivalent to
-- running 001 + 003 + 004 together.
--
-- USE THIS WHEN:  you wiped the database (test mode) and want everything back.
--   1. Run THIS file  (creates all tables + indexes)
--   2. Run 005_seed_marketplace.sql  (fills the 4 marketplaces with demo data)
--   That's it — you do NOT also need 001 / 003 / 004 (they're folded in here).
--
-- Everything is IF NOT EXISTS / ADD COLUMN IF NOT EXISTS, so running it on a DB
-- that already has these tables is harmless (it just fills any gaps).
--
-- Conventions:
--   • TEXT primary keys (UUID strings generated by the app via new_id()).
--   • Timestamps are BIGINT epoch-milliseconds.
--   • marketplace_type / store_type ∈ ('grocery','fruits','electronics','pharmacy').
-- ============================================================================


-- ── users ───────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS users (
    uid               TEXT PRIMARY KEY,            -- Firebase UID
    phone             TEXT,
    name              TEXT,
    email             TEXT,
    fcm_token         TEXT,
    address           JSONB,                       -- default delivery address
    saved_addresses   JSONB DEFAULT '[]',          -- list of saved address objects
    role              TEXT DEFAULT 'customer',     -- customer | store_owner | delivery | admin
    store_id          TEXT,                        -- set when role = store_owner
    language          TEXT DEFAULT 'en',
    is_active         BOOLEAN DEFAULT true,
    created_at        BIGINT DEFAULT 0             -- epoch ms
);


-- ── stores ──────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS stores (
    id                   TEXT PRIMARY KEY,
    owner_uid            TEXT,
    owner_name           TEXT,
    shop_name            TEXT,
    name                 TEXT,                     -- alias used in admin onboard flow
    store_type           TEXT DEFAULT 'grocery',   -- grocery|fruits|electronics|pharmacy (which marketplace)
    area                 TEXT,
    phone                TEXT,
    email                TEXT,
    address              TEXT,
    geohash6             TEXT,                     -- geohash precision-6 of store location
    location             JSONB,                    -- {lat, lng, geohash}
    is_open              BOOLEAN DEFAULT false,
    is_active            BOOLEAN DEFAULT true,
    is_verified          BOOLEAN DEFAULT false,
    is_suspended         BOOLEAN DEFAULT false,
    strike_count         INT DEFAULT 0,
    total_strikes        INT DEFAULT 0,
    suspension_end_date  BIGINT,
    available_item_ids   JSONB DEFAULT '[]',
    total_orders_accepted INT DEFAULT 0,
    total_orders_failed  INT DEFAULT 0,
    onboarded_by         TEXT,
    rating               FLOAT DEFAULT 0.0,
    fcm_token            TEXT,
    operating_hours      JSONB,
    self_delivery        BOOLEAN DEFAULT false,    -- owner delivers own orders (shares live GPS)
    image_url            TEXT DEFAULT '',
    onboarding_date      BIGINT,
    inventory            JSONB DEFAULT '{}',       -- {item_id: {qty, is_available}}
    updated_at           BIGINT,
    deleted_at           BIGINT,
    created_at           BIGINT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_stores_geohash ON stores(geohash6);
CREATE INDEX IF NOT EXISTS idx_stores_owner   ON stores(owner_uid);
CREATE INDEX IF NOT EXISTS idx_stores_active  ON stores(is_active, is_open, is_verified);
CREATE INDEX IF NOT EXISTS idx_stores_type    ON stores(store_type);


-- ── catalog_items (master product catalog, marketplace-aware) ────────────────
CREATE TABLE IF NOT EXISTS catalog_items (
    id               TEXT PRIMARY KEY,
    name             TEXT NOT NULL,
    name_hindi       TEXT DEFAULT '',
    name_marathi     TEXT DEFAULT '',
    category         TEXT,                          -- legacy free-text category label
    marketplace_type TEXT DEFAULT 'grocery',        -- grocery|fruits|electronics|pharmacy
    category_id      TEXT,                          -- FK → categories.id
    subcategory_id   TEXT,                          -- FK → subcategories.id
    brand            TEXT DEFAULT '',
    sku              TEXT DEFAULT '',
    description      TEXT DEFAULT '',
    price            FLOAT DEFAULT 0,               -- sale price
    mrp              FLOAT DEFAULT 0,               -- struck-through MRP
    discount_percent FLOAT DEFAULT 0,               -- % OFF
    stock_quantity   INT DEFAULT 0,
    unit             TEXT,
    is_active        BOOLEAN DEFAULT true,
    image_url        TEXT DEFAULT '',               -- primary image (list cards)
    images           JSONB DEFAULT '[]',            -- 3-5 image URLs (detail carousel)
    specs            JSONB DEFAULT '{}',            -- key→value: RAM/Storage/Battery/Warranty / nutrition / healthcare
    group_id         TEXT,                          -- SKU family: unit-variants (10kg/5kg/1kg) share this
    rating           FLOAT DEFAULT 0,               -- avg product rating
    rating_count     INT   DEFAULT 0,               -- number of ratings
    created_at       BIGINT DEFAULT 0,
    updated_at       BIGINT
);

CREATE INDEX IF NOT EXISTS idx_catalog_active      ON catalog_items(is_active);
CREATE INDEX IF NOT EXISTS idx_catalog_category    ON catalog_items(category);
CREATE INDEX IF NOT EXISTS idx_catalog_marketplace ON catalog_items(marketplace_type);
CREATE INDEX IF NOT EXISTS idx_catalog_category_id ON catalog_items(category_id);
CREATE INDEX IF NOT EXISTS idx_catalog_subcategory ON catalog_items(subcategory_id);
CREATE INDEX IF NOT EXISTS idx_catalog_group       ON catalog_items(group_id);


-- ── categories (admin-managed, DB-driven taxonomy) ──────────────────────────
CREATE TABLE IF NOT EXISTS categories (
    id               TEXT PRIMARY KEY,
    marketplace_type TEXT NOT NULL DEFAULT 'grocery',
    name             TEXT NOT NULL,
    image_url        TEXT DEFAULT '',
    sort_order       INT  DEFAULT 0,
    is_enabled       BOOLEAN DEFAULT true,
    created_at       BIGINT DEFAULT 0,
    updated_at       BIGINT
);

CREATE INDEX IF NOT EXISTS idx_categories_market  ON categories(marketplace_type, sort_order);
CREATE INDEX IF NOT EXISTS idx_categories_enabled ON categories(is_enabled);


-- ── subcategories (admin-managed, parent = categories.id) ───────────────────
CREATE TABLE IF NOT EXISTS subcategories (
    id               TEXT PRIMARY KEY,
    category_id      TEXT NOT NULL,
    marketplace_type TEXT NOT NULL DEFAULT 'grocery',
    name             TEXT NOT NULL,
    image_url        TEXT DEFAULT '',
    sort_order       INT  DEFAULT 0,
    is_enabled       BOOLEAN DEFAULT true,
    created_at       BIGINT DEFAULT 0,
    updated_at       BIGINT
);

CREATE INDEX IF NOT EXISTS idx_subcategories_cat     ON subcategories(category_id, sort_order);
CREATE INDEX IF NOT EXISTS idx_subcategories_market  ON subcategories(marketplace_type);
CREATE INDEX IF NOT EXISTS idx_subcategories_enabled ON subcategories(is_enabled);


-- ── marketplaces (admin-configurable verticals; DB-driven tabs/theme) ────────
CREATE TABLE IF NOT EXISTS marketplaces (
    wire                TEXT PRIMARY KEY,          -- marketplace_type value
    name                TEXT NOT NULL,
