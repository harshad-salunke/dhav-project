-- ── orders ──────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS orders (
    id                       TEXT PRIMARY KEY,
    order_id                 TEXT,               -- same as id, for JSON response compatibility
    customer_id              TEXT,
    accepted_by_store_id     TEXT,
    assigned_delivery_boy_id TEXT,
    delivery_boy_name        TEXT,
    delivery_boy_phone       TEXT,
    status                   TEXT DEFAULT 'pending',
    marketplace_type         TEXT DEFAULT 'grocery',  -- drives type-correct broadcast routing
    items                    JSONB DEFAULT '[]',
    customer_address         JSONB,
    total_product_amount     FLOAT DEFAULT 0,
    delivery_fee             FLOAT DEFAULT 0,
    total_customer_amount    FLOAT DEFAULT 0,
    platform_fee_percentage  FLOAT DEFAULT 5.0,
    platform_fee_amount      FLOAT DEFAULT 0,
    platform_fee_settled     BOOLEAN DEFAULT false,
    payment_method           TEXT DEFAULT 'cod',
    broadcast_wave           INT DEFAULT 0,
    broadcast_radius_km      FLOAT DEFAULT 0,
    broadcast_store_ids      JSONB DEFAULT '[]',
    rejected_store_ids       JSONB DEFAULT '[]',
    timed_out_store_ids      JSONB DEFAULT '[]',
    accepted_at              BIGINT,
    ws_channel_id            TEXT,
    estimated_delivery_minutes INT DEFAULT 30,
    delivered_at             BIGINT,
    failure_reason           TEXT,
    has_review               BOOLEAN DEFAULT false,
    is_direct_order          BOOLEAN DEFAULT false,
    broadcast_started_at     BIGINT,
    gstin                    TEXT  DEFAULT '',        -- optional GSTIN for B2B invoice
    donation_amount          FLOAT DEFAULT 0,         -- round-up donation added at checkout
    handling_charge          FLOAT DEFAULT 0,         -- flat handling fee shown on the bill
    delivery_instructions    JSONB DEFAULT '[]',      -- ["avoid_calling","no_bell",...]
    created_at               BIGINT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_orders_customer     ON orders(customer_id);
CREATE INDEX IF NOT EXISTS idx_orders_store        ON orders(accepted_by_store_id);
CREATE INDEX IF NOT EXISTS idx_orders_status       ON orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_delivery_boy ON orders(assigned_delivery_boy_id);


-- ── delivery_boys ───────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS delivery_boys (
    id                   TEXT PRIMARY KEY,
    uid                  TEXT,
    store_id             TEXT,
    name                 TEXT,
    phone                TEXT,
    google_account_email TEXT,
    is_active            BOOLEAN DEFAULT true,
    current_order_id     TEXT,
    created_at           BIGINT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_delivery_boys_store ON delivery_boys(store_id);
CREATE INDEX IF NOT EXISTS idx_delivery_boys_uid   ON delivery_boys(uid);
CREATE INDEX IF NOT EXISTS idx_delivery_boys_email ON delivery_boys(lower(google_account_email));


-- ── strike_logs ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS strike_logs (
    id             TEXT PRIMARY KEY,
    store_id       TEXT,
    order_id       TEXT,
    reason         TEXT,
    strike_number  INT,
    action_taken   TEXT,
    created_at     BIGINT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_strikes_store ON strike_logs(store_id);


-- ── settlements ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS settlements (
    id                      TEXT PRIMARY KEY,
    store_id                TEXT,
    week_start              TEXT,               -- ISO date string "2026-01-06"
    week_end                TEXT,
    total_orders_delivered  INT DEFAULT 0,
    total_platform_fee_owed FLOAT DEFAULT 0,
    total_fee_paid          FLOAT DEFAULT 0,
    balance_due             FLOAT DEFAULT 0,
    status                  TEXT DEFAULT 'pending',
    is_overdue              BOOLEAN DEFAULT false,
    payment_records         JSONB DEFAULT '[]',
    created_at              BIGINT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_settlements_store  ON settlements(store_id);
CREATE INDEX IF NOT EXISTS idx_settlements_status ON settlements(status);


-- ── admin_users ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS admin_users (
    uid        TEXT PRIMARY KEY,
    role       TEXT DEFAULT 'admin',
    created_at BIGINT DEFAULT 0
);


-- ── custom_item_requests (store asks admin to add a product) ────────────────
CREATE TABLE IF NOT EXISTS custom_item_requests (
    id               TEXT PRIMARY KEY,
    store_id         TEXT,
    requested_by_uid TEXT,
    name             TEXT,
    name_hindi       TEXT DEFAULT '',
    name_marathi     TEXT DEFAULT '',
    category         TEXT,
    unit             TEXT,
    price            FLOAT DEFAULT 0,
    notes            TEXT DEFAULT '',
    status           TEXT DEFAULT 'pending',
    created_at       BIGINT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_custom_requests_store  ON custom_item_requests(store_id);
CREATE INDEX IF NOT EXISTS idx_custom_requests_status ON custom_item_requests(status);


-- ── reviews ─────────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS reviews (
    id          TEXT PRIMARY KEY,
    order_id    TEXT,
    store_id    TEXT,
    customer_id TEXT,
    rating      INT,
    comment     TEXT DEFAULT '',
    created_at  BIGINT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_reviews_store ON reviews(store_id);


-- ── notifications ───────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS notifications (
    id         TEXT PRIMARY KEY,
    uid        TEXT,               -- recipient user uid
    title      TEXT,
    body       TEXT,
    type       TEXT DEFAULT 'announcement',
    order_id   TEXT,
    is_read    BOOLEAN DEFAULT false,
    sender     TEXT DEFAULT 'system',
    created_at BIGINT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_notifications_uid   ON notifications(uid);
CREATE INDEX IF NOT EXISTS idx_notifications_order ON notifications(order_id);


-- ── coming_soon_waitlist ("Notify me" demand for unserved areas) ────────────
CREATE TABLE IF NOT EXISTS coming_soon_waitlist (
    id          TEXT PRIMARY KEY,           -- uuid string (new_id())
    uid         TEXT NOT NULL,              -- Firebase UID of the requesting customer
    area        TEXT DEFAULT '',            -- reverse-geocoded area label (context only)
    lat         DOUBLE PRECISION,           -- the spot the customer wanted served
    lng         DOUBLE PRECISION,
    notified    BOOLEAN DEFAULT false,      -- set true once we ping them a store went live
    created_at  BIGINT DEFAULT 0,           -- epoch ms (last request)
    UNIQUE (uid, area)                      -- one active request per (customer, area)
);

CREATE INDEX IF NOT EXISTS idx_waitlist_area     ON coming_soon_waitlist(area);
CREATE INDEX IF NOT EXISTS idx_waitlist_notified ON coming_soon_waitlist(notified);


-- ── wishlist (saved-for-later, per customer) ────────────────────────────────
CREATE TABLE IF NOT EXISTS wishlist (
    uid        TEXT NOT NULL,            -- Firebase UID of the customer
    item_id    TEXT NOT NULL,            -- catalog_items.id
    created_at BIGINT DEFAULT 0,         -- epoch ms
    PRIMARY KEY (uid, item_id)
);

CREATE INDEX IF NOT EXISTS idx_wishlist_uid ON wishlist(uid);


